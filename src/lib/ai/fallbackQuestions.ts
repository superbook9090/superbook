/**
 * Returns a high-quality fallback Mixed GK & GS contest theme and questions.
 * Ensures the contest is ALWAYS a balanced Mixed GK & GS set with zero single-topic narrowness.
 */
export function getFallbackContestData(targetQuestions = 10): FallbackContestTheme {
  const themeIndex = Math.floor(Math.random() * FALLBACK_CONTEST_THEMES.length);
  const selectedTheme = FALLBACK_CONTEST_THEMES[themeIndex];

  // Shuffle questions array within the balanced pool
  const shuffledQuestions = [...selectedTheme.questions].sort(() => Math.random() - 0.5);
  const selectedQuestions = shuffledQuestions.slice(0, targetQuestions);

  // If pool has fewer than target, top up from another theme
  if (selectedQuestions.length < targetQuestions) {
    for (const otherTheme of FALLBACK_CONTEST_THEMES) {
      if (otherTheme === selectedTheme) continue;
      for (const q of otherTheme.questions) {
        if (!selectedQuestions.some((sq) => sq.question === q.question)) {
          selectedQuestions.push({ ...q });
          if (selectedQuestions.length >= targetQuestions) break;
        }
      }
      if (selectedQuestions.length >= targetQuestions) break;
    }
  }

  // Generate unique slug with date/timestamp to prevent unique index collision
  const dateStr = new Date().toISOString().slice(0, 10);
  const randomSuffix = Math.random().toString(36).substring(2, 6);
  const uniqueSlug = `daily-mixed-gk-gs-contest-${dateStr}-${randomSuffix}`;

  return {
    topic: selectedTheme.topic,
    slug: uniqueSlug,
    metaTitle: selectedTheme.metaTitle,
    metaDescription: selectedTheme.metaDescription,
    questions: selectedQuestions.slice(0, targetQuestions),
  };
}
